def seed_default_room_types():
    """Seeds default room types if missing, preserving existing data."""
    ensure_room_type_columns(engine)
    created = 0
    with SessionLocal() as db:
        for item in DEFAULT_ROOM_TYPES:
            # Check if exists by name or prefix
            base_name = item["name"].replace(" Room", "").strip()
            existing = db.scalar(
                select(RoomType).where(
                    or_(
                        RoomType.name == item["name"],
                        RoomType.name == base_name,
                        RoomType.slug == item["slug"],
                    )
                )
            )
            if existing:
                # Room type already exists; preserve user edits and update any empty columns
                updated = False
                if not existing.slug:
                    existing.slug = item["slug"]; updated = True
                if not existing.short_description:
                    existing.short_description = item["short_description"]; updated = True
                if not existing.image_url:
                    existing.image_url = item["image_url"]; updated = True
                if not existing.status:
                    existing.status = "Active"; updated = True
                if updated:
                    db.commit()
                continue

            # Add new room type
            data = dict(item)
            data["amenities"] = json.dumps(data["amenities"])
            rt = RoomType(**data)
            db.add(rt)
            created += 1
        db.commit()
    print(f"Room types check complete: {created} new room types created.")
    return created

if __name__ == "__main__":
    seed_default_room_types()
